function ChallengerPicker({
  models,
  baseModelId,
  picked,
  maxChallengers,
  onChange,
}: {
  models: FormModel[];
  baseModelId: string;
  picked: string[];
  maxChallengers: number;
  onChange: (modelIds: string[]) => void;
}) {
  const [query, setQuery] = useState('');
  const [weight, setWeight] = useState<ModelWeightFilter>('all');
  const [showPrevious, setShowPrevious] = useState(false);
  const searching = query.trim().length > 0;
  const view = useMemo(
    () =>
      buildModelPickerView({
        models,
        selectedIds: picked,
        query,
        weight,
        showPrevious,
      }),
    [models, picked, query, weight, showPrevious],
  );

  const toggle = (modelId: string) =>
    onChange(toggleChallenger(modelId, baseModelId || null, picked, maxChallengers));

  const renderSection = (section: (typeof view.sections)[number]) => (
      <div
        key={section.key}
        className="flex flex-col gap-[6px]"
        data-model-section={section.key}
      >
        <h3 className="m-0 text-[10.5px] font-medium uppercase tracking-[0.08em] text-neutral-400">
          {section.label}
        </h3>
        <div className="grid grid-cols-[repeat(auto-fill,minmax(190px,1fr))] gap-[6px]">
          {section.models.map((model) => {
            const isBase = model.id === baseModelId;
            const selected = picked.includes(model.id);
            const disabled = challengerDisabled(
              model.id,
              baseModelId || null,
              picked,
              maxChallengers,
            );

            return (
              <button
                key={model.id}
                type="button"
                aria-pressed={selected}
                disabled={disabled}
                data-model-weight={model.openWeights ? 'open' : 'frontier'}
                onClick={() => toggle(model.id)}
                className={cn(
                  'flex items-center gap-[9px] rounded-[2px] border p-[9px] text-left text-text transition-colors',
                  selected
                    ? 'border-accent bg-accent-900'
                    : 'border-neutral-800 bg-surface',
                  disabled
                    ? 'cursor-not-allowed opacity-45'
                    : 'cursor-pointer hover:border-accent-700',
                )}
              >
                <span
                  className={cn(
                    'grid h-6 w-6 flex-none place-items-center rounded-[2px] text-[10.5px] font-semibold text-neutral-100',
                    selected ? 'bg-accent-800' : 'bg-neutral-700',
                  )}
                >
                  {model.monogram}
                </span>
                <span className="flex min-w-0 flex-1 flex-col gap-[2px]">
                  <span className="flex min-w-0 items-center gap-[5px]">
                    <span className="truncate text-[12.5px] font-medium">
                      {model.displayName}
                    </span>
                    {model.release === 'previous' && (
                      <span
                        data-previous-badge
                        className="flex-none rounded-[2px] border border-neutral-600 px-1 py-px text-[10.5px] font-medium uppercase tracking-[0.04em] text-neutral-400"
                      >
                        Previous
                      </span>
                    )}
                  </span>
                  <span className="text-[11px] font-normal text-neutral-500">
                    {isBase
                      ? `Base model · ${modelWeightLabel(model.openWeights)}`
                      : `${modelWeightLabel(model.openWeights)} · ~${model.etaSeconds}s`}
                  </span>
                </span>
                <span
                  className={cn(
                    'grid h-4 w-4 flex-none place-items-center rounded-[2px] border',
                    selected ? 'border-accent bg-accent' : 'border-neutral-600',
                  )}
                >
                  {selected && <Check size={11} weight="bold" className="text-bg" />}
                </span>
              </button>
            );
          })}
        </div>
      </div>
  );
  const currentSections = view.sections.filter(
    (section) => section.key !== 'previous',
  );
  const previousSection = view.sections.find(
    (section) => section.key === 'previous',
  );

  return (
    <div className="flex flex-col gap-[10px]">
      <div className="flex flex-col gap-[8px] sm:flex-row sm:items-end">
        <label className="flex min-w-0 flex-1 flex-col gap-[5px]">
          <span className="text-[11px] font-medium text-neutral-400">Search models</span>
          <input
            type="search"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Search by name, family or slug…"
            className="h-8 w-full rounded-[2px] border border-neutral-700 bg-bg px-2 text-[12px] font-normal text-text placeholder:text-neutral-500 focus:border-accent"
          />
        </label>
        <SegmentedControl
          label="Filter by weights"
          className="self-start"
          value={weight}
          options={WEIGHT_FILTERS}
          onChange={setWeight}
        />
      </div>

      {view.selected.length > 0 && (
        <div className="flex flex-col gap-[5px]" data-selected-models>
          <span className="text-[10.5px] font-medium uppercase tracking-[0.08em] text-neutral-400">
            SELECTED
          </span>
          <div className="flex flex-wrap gap-[5px]">
            {view.selected.map((model) => (
              <button
                key={model.id}
                type="button"
                aria-pressed
                onClick={() => toggle(model.id)}
                title={`Remove ${model.displayName}`}
                className="flex items-center gap-[5px] rounded-[2px] border border-accent bg-accent-900 py-[3px] pl-[3px] pr-[6px] text-[11px] font-medium text-text transition-colors hover:border-accent-700"
              >
                <span className="grid h-[18px] w-[18px] place-items-center rounded-[2px] bg-accent-800 text-[9px] font-semibold text-neutral-100">
                  {model.monogram}
                </span>
                <span className="max-w-[180px] truncate">{model.displayName}</span>
                <X size={10} className="flex-none text-neutral-400" />
              </button>
            ))}
          </div>
        </div>
      )}

      {currentSections.map(renderSection)}

      {view.empty && (
        <p
          role="status"
          className="rounded-[2px] border border-neutral-800 bg-surface px-3 py-2 text-[12px] font-normal leading-[1.45] text-neutral-400"
        >
          {view.empty === 'registry'
            ? 'No models are available. Ask an Admin to enable one.'
            : searching
              ? `No models match “${query.trim()}”.`
              : 'No models match these filters.'}
        </p>
      )}

      {view.previousMatches > 0 && !searching && (
        <button
          type="button"
          aria-expanded={showPrevious}
          onClick={() => setShowPrevious((current) => !current)}
          className="flex items-center gap-[5px] self-start rounded-[2px] border border-neutral-700 px-[9px] py-[5px] text-[11px] font-medium text-neutral-300 transition-colors hover:border-accent-700 hover:text-accent-200"
        >
          {showPrevious
            ? `Hide previous releases (${view.previousMatches})`
            : `Show previous releases (${view.previousMatches})`}
          <CaretDown
            size={11}
            className={cn('transition-transform', showPrevious && 'rotate-180')}
          />
        </button>
      )}

      {previousSection && renderSection(previousSection)}
    </div>
  );
}

export function NewComparisonClient({
  models,
  handle,
  maxChallengers,
}: {
  models: FormModel[];
  handle: string;
  maxChallengers: number;
}) {
  const router = useRouter();
  const inputRef = useRef<HTMLInputElement>(null);
  const titleTouched = useRef(false);
  const [baseSource, setBaseSource] = useState<BaseSource>('upload');
  const [loaded, setLoaded] = useState<LoadedFile | null>(null);
  const [baseOutput, setBaseOutput] = useState('');
  const [baseModelId, setBaseModelId] = useState('');
  const [prompt, setPrompt] = useState('');
  const [title, setTitle] = useState('');
  const [picked, setPicked] = useState<string[]>([]);
  const [categories, setCategories] = useState<string[]>([]);
  const [effort, setEffort] = useState(2);
  const [dragging, setDragging] = useState(false);
  const [fileError, setFileError] = useState<FormError | null>(null);
  const [modelNotice, setModelNotice] = useState<string | null>(null);
  const [submitError, setSubmitError] = useState<FormError | null>(null);
  const [submitting, setSubmitting] = useState(false);

  // The upload tab compares every Turn; the write tab is always one Turn.
  const turnCount =
    baseSource === 'upload' ? loaded?.imported.turns.length ?? 1 : 1;
  const schedule = describeSchedule({
    baseSource,
    hasFile: Boolean(loaded),
    hasBaseOutput: Boolean(baseOutput.trim()),
    baseModelId: baseModelId || null,
    challengerIds: picked,
    prompt,
    turnCount,
    models,
  });
  const baseModel = models.find((model) => model.id === baseModelId) ?? null;
  const pickedModels = picked
    .map((id) => models.find((model) => model.id === id))
    .filter((model): model is FormModel => Boolean(model));
  const hasBase = baseSource === 'upload' ? Boolean(loaded) : Boolean(baseOutput.trim());
  const baseBody =
    baseSource === 'upload' ? loaded?.imported.turns[0]?.baseOutput : baseOutput;
  const baseSnippet = baseBody?.trim()
    ? summariseMarkdown(baseBody, 180)
    : undefined;
  const previewTurns: ConversationTurnInput[] = (loaded?.imported.turns ?? []).map(
    (turn, index) =>
      index === 0 && loaded?.imported.format !== 'ai-exporter'
        ? { ...turn, prompt }
        : turn,
  );
  const estimatedTokens = estimateConversationInputTokens(previewTurns);
  const estimatedCalls = estimateConversationCalls(
    previewTurns.length,
    picked.length,
  );

  async function loadFile(
    nextFile: File,
    overrides?: { title?: string; categories?: string[] },
  ) {
    setFileError(null);
    try {
      validateFileSize(nextFile.size);
      const text = decodeUtf8(new Uint8Array(await nextFile.arrayBuffer()));
      const imported = parseConversationUpload(text, nextFile.name);
      const matched = matchModelFromFrontMatter(imported.model, models);
      const vendorMatches = matchVendorModels(imported.vendor, models);
      const soleVendorMatch =
        vendorMatches.length === 1 ? vendorMatches[0]! : null;

      setLoaded({
        file: nextFile,
        imported,
        sizeLabel: sizeLabel(nextFile.size, text),
      });
      setPrompt(imported.turns[0]?.prompt ?? imported.prompt ?? '');
      setTitle(overrides?.title ?? defaultTitleForImport(imported));
      titleTouched.current = Boolean(overrides?.title);
      if (overrides?.categories) setCategories(overrides.categories);

      if (matched) {
        setBaseModelId(matched.id);
        setPicked((current) => current.filter((id) => id !== matched.id));
        setModelNotice(null);
      } else if (soleVendorMatch) {
        setBaseModelId(soleVendorMatch.id);
        setPicked((current) => current.filter((id) => id !== soleVendorMatch.id));
        setModelNotice(
          `This looks like a ${vendorLabel(imported.vendor)} conversation, so we selected ${soleVendorMatch.displayName}. Change it if another model wrote the replies.`,
        );
      } else if (imported.vendor) {
        setBaseModelId('');
        const name = vendorLabel(imported.vendor);
        setModelNotice(
          vendorMatches.length > 1
            ? `This looks like a ${name} conversation, which matches ${vendorMatches.length} models in the registry. Choose the one that generated the replies.`
            : `This looks like a ${name} conversation, but no registry model matches it. Choose the model that generated the replies.`,
        );
      } else if (imported.model) {
        setBaseModelId('');
        setModelNotice(
          `We couldn't match “${imported.model}” to a model in the registry. Choose the model that generated this output.`,
        );
      } else {
        setModelNotice(null);
      }
    } catch (error) {
      setFileError(
        error instanceof UploadValidationError
          ? { code: error.code, message: error.message }
          : {
              code: 'unreadable_file',
              message:
                'That file could not be read as text. Export the conversation as markdown and try again.',
            },
      );
    }
  }

  function pickFile(file: File | undefined) {
    if (file) void loadFile(file);
  }

  function changePrompt(next: string) {
    setPrompt(next);
    // A bare markdown upload has no Prompt until the author types one, so keep
    // following it with the default title until the title is edited by hand.
    if (!titleTouched.current) {
      setTitle(summariseMarkdown(next, 80) || loaded?.imported.titleFromFile || '');
    }
  }

  function chooseBaseModel(next: string) {
    setBaseModelId(next);
    setModelNotice(null);
    setPicked((current) => current.filter((id) => id !== next));
  }

  function toggleCategory(category: string) {
    setCategories((current) =>
      current.includes(category)
        ? current.filter((value) => value !== category)
        : [...current, category],
    );
  }

  async function submit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!schedule.ready || submitting) return;

    setSubmitError(null);
    setSubmitting(true);

    try {
      const body = new FormData();
      if (baseSource === 'upload' && loaded) {
        body.set('file', loaded.file);
      } else {
        body.set('base_output', baseOutput);
      }
      body.set('base_model_id', baseModelId);
      body.set('prompt', prompt);
      body.set('title', title);
      body.set('effort', String(effort));
      for (const category of categories) body.append('categories', category);
      for (const modelId of picked) body.append('model_ids', modelId);

      const response = await fetch('/api/comparisons', { method: 'POST', body });
      const payload = (await response.json().catch(() => null)) as
        | { id?: string; error?: { code?: string; message?: string } }
        | null;

      if (!response.ok || !payload?.id) {
        const failure = new Error(
          payload?.error?.message ?? 'Could not schedule this comparison. Try again.',
        ) as Error & { code?: string };
        failure.code = payload?.error?.code;
        throw failure;
      }

      router.push(`/comparisons/${payload.id}/job`);
    } catch (error) {
      setSubmitError({
        code:
          error instanceof UploadValidationError
            ? error.code
            : error instanceof Error && 'code' in error && error.code
              ? String(error.code)
              : 'schedule_failed',
        message:
          error instanceof Error
            ? error.message
            : 'Could not schedule this comparison. Try again.',
      });
      setSubmitting(false);
    }
  }

  return (
    <div className="flex min-h-screen flex-col">
      <SiteHeader handle={handle} variant="page" showNew={false} />

      <main className="mx-auto grid w-full max-w-[1120px] grid-cols-1 gap-8 px-5 pb-14 pt-[22px] lg:grid-cols-[minmax(0,1fr)_300px]">
        <form onSubmit={submit} className="flex min-w-0 flex-col gap-[26px]">
          <div className="flex flex-col gap-1">
            <h1 className="m-0 font-heading text-[18px] font-medium leading-[1.2] tracking-[-0.015em]">
              New comparison
            </h1>
            <span className="text-[12px] font-normal text-neutral-400">
              Upload a conversation or write one prompt, then pick who to compare it
              against. We&apos;ll send every turn to each model&apos;s hosted API.
            </span>
          </div>

          <section className="flex flex-col gap-[10px]">
            <Step
              number={1}
              label="Base output"
              done={hasBase && Boolean(baseModelId)}
              active={!hasBase || !baseModelId}
            />

            <SegmentedControl
              label="Base output source"
              className="self-start"
              value={baseSource}
              options={[
                { value: 'upload', label: 'Upload a conversation' },
                { value: 'write', label: 'Write a prompt' },
              ]}
              onChange={(next) => {
                setBaseSource(next);
                setSubmitError(null);
              }}
            />

            <input
              ref={inputRef}
              type="file"
              accept=".md,.markdown,.txt"
              aria-label="Base output file"
              className="sr-only"
              onChange={(event) => {
                pickFile(event.target.files?.[0]);
                event.target.value = '';
              }}
            />

            {baseSource === 'upload' ? (
              <>
                {!loaded ? (
                  <>
                    <button
                      type="button"
                      onClick={() => inputRef.current?.click()}
                      onDragOver={(event) => {
                        event.preventDefault();
                        setDragging(true);
                      }}
                      onDragLeave={() => setDragging(false)}
                      onDrop={(event) => {
                        event.preventDefault();
                        setDragging(false);
                        pickFile(event.dataTransfer.files[0]);
                      }}
                      className={cn(
                        'flex flex-col items-start gap-[6px] rounded-[2px] border border-dashed bg-transparent p-5 text-left transition-colors focus-within:outline-2 focus-within:outline-accent focus-within:outline-offset-2',
                        dragging
                          ? 'border-accent bg-accent-900'
                          : 'border-neutral-600 hover:border-accent-700',
                      )}
                    >
                      <FileArrowUp size={22} className="text-accent-300" />
                      <span className="text-[12px] font-medium">
                        Drop a .md file, or{' '}
                        <span className="text-accent-300">browse</span>
                      </span>
                      <span className="text-[12px] font-normal text-neutral-500">
                        AI Exporter, front-matter{' '}
                        <code className="font-mono">prompt:</code> and plain markdown are
                        read automatically
                      </span>
                    </button>
                    <HowToGetThisFile />
                  </>
                ) : (
                  <div className="flex flex-col gap-[10px] rounded-[2px] bg-surface p-3">
                    <div className="flex items-center gap-[10px]">
                      <FileText size={20} className="flex-none text-accent-300" />
                      <div className="flex min-w-0 flex-1 flex-col gap-[2px]">
                        <span className="truncate text-[12px] font-medium">
                          {loaded.file.name}
                        </span>
                        <span className="text-[11px] font-normal text-neutral-500">
                          {loaded.sizeLabel} · {plural(previewTurns.length, 'turn')}
                        </span>
                      </div>
                      <button
                        type="button"
                        onClick={() => inputRef.current?.click()}
                        className="btn-ghost h-[26px] px-2 text-[12px]"
                      >
                        Replace
                      </button>
                    </div>

                    <div
                      className={cn(
                        'grid grid-cols-1 gap-[10px]',
                        loaded.imported.format !== 'ai-exporter' &&
                          'sm:grid-cols-[minmax(0,220px)_minmax(0,1fr)]',
                      )}
                    >
                      <BaseModelSelect
                        models={models}
                        value={baseModelId}
                        onChange={chooseBaseModel}
                      />

                      {loaded.imported.format !== 'ai-exporter' && (
                        <PromptEditor
                          value={prompt}
                          onChange={changePrompt}
                          label={`Prompt${loaded.imported.prompt ? ' · from front-matter' : ''}`}
                        />
                      )}
                    </div>

                    <section
                      aria-label={`Imported ${plural(previewTurns.length, 'turn')}`}
                      className="flex flex-col gap-[6px]"
                    >
                      <div className="flex items-baseline justify-between gap-2">
                        <span className="text-[11px] font-medium text-neutral-400">
                          Check every turn before scheduling
                        </span>
                        <span className="text-[11px] font-normal text-neutral-500">
                          {plural(previewTurns.length, 'turn')}
                        </span>
                      </div>

                      <ol className="flex flex-col gap-[5px]">
                        {previewTurns.map((turn, index) => (
                          <li
                            key={`${index}-${turn.prompt.slice(0, 12)}`}
                            className="rounded-[2px] border border-neutral-800 bg-bg p-[9px]"
                          >
                            <div className="flex items-center gap-[6px] text-[11px] font-medium">
                              <span className="rounded-[2px] bg-neutral-700 px-[5px] py-px text-[10.5px] text-neutral-100">
                                Turn {index + 1}
                              </span>
                              <span className="text-neutral-400">You</span>
                            </div>
                            <p className="mt-[5px] line-clamp-2 text-[12px] font-normal leading-[1.45] text-text">
                              {summariseMarkdown(turn.prompt, 220) ||
                                'The Prompt field above will be used.'}
                            </p>
                            <div className="mt-[7px] flex items-center gap-[6px] text-[11px] font-medium">
                              <span className="text-neutral-400">
                                {loaded.imported.vendors[index]
                                  ? vendorLabel(loaded.imported.vendors[index]!)
                                  : 'Reply'}
                              </span>
                            </div>
                            <p className="mt-[3px] line-clamp-3 text-[12px] font-normal leading-[1.45] text-neutral-300">
                              {summariseMarkdown(turn.baseOutput, 300)}
                            </p>
                          </li>
                        ))}
                      </ol>
                    </section>

                    {loaded.imported.warnings.map((warning) => (
                      <p
                        key={`${warning.code}-${warning.message}`}
                        role="status"
                        className="flex items-start gap-[6px] text-[11px] font-normal leading-[1.45] text-neutral-200"
                      >
                        <WarningCircle size={13} className="mt-px flex-none text-accent-300" />
                        {warning.message}
                      </p>
                    ))}

                    <p className="text-[11px] font-normal leading-[1.45] text-neutral-500">
                      {plural(previewTurns.length, 'turn')}
                      {picked.length
                        ? ` × ${plural(picked.length, 'model')} = ${plural(estimatedCalls, 'call')}`
                        : ''}{' '}
                      · ~{estimatedTokens.toLocaleString('en-US')} input tokens per model
                    </p>
                    <p className="text-[11px] font-normal leading-[1.45] text-neutral-500">
                      Limits: {LIMITS_LABEL}
                    </p>

                    {modelNotice && (
                      <p
                        role="status"
                        className="flex items-start gap-[6px] text-[11px] font-normal leading-[1.45] text-neutral-300"
                      >
                        <WarningCircle size={13} className="mt-px flex-none text-accent-300" />
                        {modelNotice}
                      </p>
                    )}
                  </div>
                )}
              </>
            ) : (
              <div className="flex flex-col gap-[10px] rounded-[2px] bg-surface p-3">
                <BaseModelSelect
                  models={models}
                  value={baseModelId}
                  onChange={chooseBaseModel}
                />

                <PromptEditor
                  value={prompt}
                  onChange={changePrompt}
                  label="Prompt"
                  rows={3}
                  placeholder="Ask the model something…"
                />

                <label className="flex flex-col gap-[5px]">
                  <span className="text-[11px] font-medium text-neutral-400">
                    Base output
                  </span>
                  <textarea
                    value={baseOutput}
                    onChange={(event) => setBaseOutput(event.target.value)}
                    rows={6}
                    maxLength={MAX_BASE_OUTPUT_CHARS}
                    placeholder="Paste what the base model wrote…"
                    className="resize-y rounded-[2px] border border-neutral-700 bg-bg px-2 py-[7px] text-[12px] font-normal leading-[1.45] text-text focus:border-accent"
                  />
                </label>
              </div>
            )}

            {baseSource === 'upload' && fileError && (
              <div
                role="alert"
                className="flex flex-col gap-[3px] text-[11px] font-normal leading-[1.45] text-danger"
              >
                <p className="flex items-start gap-[6px]">
                  <WarningCircle size={13} className="mt-px flex-none" />
                  {fileError.message}
                </p>
                <Link
                  href={EXPORT_GUIDE_PATH}
                  className="ml-[19px] font-medium text-accent-300 hover:text-accent-200"
                >
                  See how to fix an export
                </Link>
              </div>
            )}
          </section>

          <section className="flex flex-col gap-[10px]">
            <div className="flex items-center gap-2">
              <Step
                number={2}
                label="Compare against"
                done={picked.length > 0}
                active={Boolean(hasBase && baseModelId) && picked.length === 0}
              />
              <div className="flex-1" />
              <span className="text-[12px] font-normal text-neutral-500">
                {picked.length} of {maxChallengers} selected
              </span>
            </div>

            <ChallengerPicker
              models={models}
              baseModelId={baseModelId}
              picked={picked}
              maxChallengers={maxChallengers}
              onChange={setPicked}
            />
          </section>

          <section className="flex flex-col gap-3">
            <Step
              number={3}
              label="Details"
              done={Boolean(title && categories.length)}
              active={picked.length > 0}
            />

            <label className="flex flex-col gap-[5px]">
              <span className="text-[11px] font-medium text-neutral-400">Title</span>
              <input
                value={title}
                onChange={(event) => {
                  titleTouched.current = true;
                  setTitle(event.target.value);
                }}
                placeholder="What's being compared?"
                maxLength={200}
                className="h-[34px] rounded-[2px] border border-neutral-700 bg-surface px-[10px] text-[12px] font-medium text-text focus:border-accent"
              />
            </label>

            <div className="flex flex-col gap-[6px]">
              <span className="text-[11px] font-medium text-neutral-400">Categories</span>
              <div className="flex flex-wrap gap-[5px]">
                {CATEGORIES.map((category) => {
                  const selected = categories.includes(category);
                  return (
                    <button
                      key={category}
                      type="button"
                      aria-pressed={selected}
                      onClick={() => toggleCategory(category)}
                      className={cn(
                        'h-[26px] rounded-[2px] border px-[10px] text-[12px] font-medium transition-colors',
                        selected
                          ? 'border-accent bg-accent-900 text-accent-200'
                          : 'border-neutral-700 bg-transparent text-neutral-300 hover:border-accent-700',
                      )}
                    >
                      {category}
                    </button>
                  );
                })}
              </div>
            </div>

            <div className="flex flex-col gap-[6px]">
              <span className="text-[11px] font-medium text-neutral-400">Effort level</span>
              <SegmentedControl
                label="Effort level"
                className="self-start"
                itemClassName="h-auto flex-col items-start justify-start gap-px px-3 py-[6px] text-left"
                value={effort}
                options={EFFORT_LEVELS.map((level) => ({
                  value: level.value,
                  label: (
                    <>
                      <span className="flex items-center gap-2 text-[12px] font-medium">
                        <EffortGlyph effort={level.value} />
                        {level.label}
                      </span>
                      <span className="text-[10.5px] font-normal text-neutral-300">
                        {level.sub}
                      </span>
                    </>
                  ),
                }))}
                onChange={(value) => setEffort(value)}
              />
            </div>
          </section>

          {submitError && (
            <div
              role="alert"
              className="flex flex-col gap-[4px] rounded-[2px] border border-danger/40 bg-danger/10 px-3 py-2 text-[12px] font-normal leading-[1.45] text-danger"
            >
              <p className="flex items-start gap-[6px]">
                <X size={14} className="mt-px flex-none" />
                {submitError.message}
              </p>
              {baseSource === 'upload' && UPLOAD_ERROR_CODES.has(submitError.code) && (
                <Link
                  href={EXPORT_GUIDE_PATH}
                  className="ml-5 font-medium text-accent-300 hover:text-accent-200"
                >
                  See how to fix an export
                </Link>
              )}
            </div>
          )}

          <div className="flex flex-wrap items-center gap-3 pt-[6px]">
            <button
              type="submit"
              disabled={!schedule.ready || submitting}
              className="flex h-9 items-center gap-[6px] rounded-[2px] border border-accent bg-accent px-4 text-[12px] font-semibold text-bg transition-colors hover:bg-accent-300 disabled:cursor-not-allowed disabled:opacity-45"
            >
              {submitting ? (
                <CircleNotch size={14} className="anim-spin" />
              ) : (
                <Lightning size={14} />
              )}
              {submitting ? 'Scheduling…' : 'Schedule comparison'}
            </button>
            <span className="text-[12px] font-normal text-neutral-500">
              {submitting ? 'Creating the job and queueing its turns…' : schedule.hint}
            </span>
          </div>
        </form>

        <ComparisonPreview
          base={
            baseModel
              ? { name: baseModel.displayName, monogram: baseModel.monogram }
              : null
          }
          challengers={pickedModels.map((model) => ({
            name: model.displayName,
            monogram: model.monogram,
          }))}
          title={title}
          categories={categories}
          effort={effort}
          baseSnippet={baseSnippet}
          status={{ label: 'Draft', tone: 'draft' }}
          handle={handle}
          note="Live preview of the card other people will see."
        />
      </main>
    </div>
  );
}
