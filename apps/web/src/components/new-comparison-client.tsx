function ChallengerPicker({
  models,
  baseModelId,
  picked,
  maxChallengers,
  onChange,
}: {
  models: FormModel[];
  baseModelId: string;
  picked: string[];
  maxChallengers: number;
  onChange: (modelIds: string[]) => void;
}) {
  const [query, setQuery] = useState('');
  const [weight, setWeight] = useState<ModelWeightFilter>('all');
  const [showPrevious, setShowPrevious] = useState(false);
  const searching = query.trim().length > 0;
  const view = useMemo(
    () =>
      buildModelPickerView({
        models,
        selectedIds: picked,
        query,
        weight,
        showPrevious,
      }),
    [models, picked, query, weight, showPrevious],
  );

  const toggle = (modelId: string) =>
    onChange(toggleChallenger(modelId, baseModelId || null, picked, maxChallengers));

  const renderSection = (section: (typeof view.sections)[number]) => (
    <div
      key={section.key}
      className="flex flex-col gap-2.5"
      data-model-section={section.key}
    >
      <MicroLabel>{section.label}</MicroLabel>
      <div className="grid grid-cols-[repeat(auto-fill,minmax(230px,1fr))] gap-2">
        {section.models.map((model) => {
          const isBase = model.id === baseModelId;
          const selected = picked.includes(model.id);
          const disabled = challengerDisabled(
            model.id,
            baseModelId || null,
            picked,
            maxChallengers,
          );

          return (
            <button
              key={model.id}
              type="button"
              aria-pressed={selected}
              disabled={disabled}
              data-model-weight={model.openWeights ? 'open' : 'frontier'}
              onClick={() => toggle(model.id)}
              className={cn(
                'flex min-h-14 items-center gap-3 rounded-xs border bg-transparent p-[10px_12px] text-left text-text transition-colors',
                selected
                  ? 'border-accent-600 bg-accent-900'
                  : 'border-neutral-700',
                disabled
                  ? 'cursor-not-allowed opacity-45'
                  : 'cursor-pointer hover:border-neutral-500',
              )}
            >
              <InitialsBadge
                initials={model.monogram}
                size={28}
                tone={selected ? 'base' : 'neutral'}
                className={selected ? undefined : 'bg-neutral-800 text-neutral-200'}
              />
              <span className="flex min-w-0 flex-1 flex-col gap-px">
                <span className="flex min-w-0 items-center gap-1.5">
                  <span className="truncate text-[14px] font-medium">
                    {model.displayName}
                  </span>
                  {model.release === 'previous' && (
                    <span
                      data-previous-badge
                      className="flex-none rounded-xs border border-neutral-600 px-1 py-px text-[10.5px] font-medium uppercase tracking-[0.04em] text-neutral-400"
                    >
                      Previous
                    </span>
                  )}
                </span>
                <span className={cn('truncate', FIELD_HINT)}>
                  {isBase
                    ? `Base model · ${modelWeightLabel(model.openWeights)}`
                    : `${modelWeightLabel(model.openWeights)} · ~${model.etaSeconds}s`}
                </span>
              </span>
              <span
                className={cn(
                  'grid h-[18px] w-[18px] flex-none place-items-center rounded-full border',
                  selected
                    ? 'border-accent bg-accent text-on-accent'
                    : 'border-neutral-600',
                )}
              >
                {selected && <Check size={11} weight="bold" aria-hidden />}
              </span>
            </button>
          );
        })}
      </div>
    </div>
  );
  const currentSections = view.sections.filter(
    (section) => section.key !== 'previous',
  );
  const previousSection = view.sections.find(
    (section) => section.key === 'previous',
  );

  return (
    <div className="flex flex-col gap-5">
      <div className="flex flex-wrap items-center gap-3">
        <div className="flex h-10 min-w-0 flex-1 basis-[260px] items-center gap-2.5 rounded-xs border border-neutral-700 bg-bg px-3 text-neutral-400 focus-within:border-accent">
          <MagnifyingGlass size={15} aria-hidden />
          <label htmlFor="model-search" className="sr-only">
            Search models
          </label>
          <input
            id="model-search"
            type="search"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Search by name, family or slug…"
            className="min-w-0 flex-1 border-0 bg-transparent p-0 text-[14px] text-text placeholder:text-neutral-400 focus-visible:outline-none"
          />
        </div>
        <SegmentedControl
          label="Filter by weights"
          className="max-w-full"
          itemClassName="h-[30px] px-2 sm:px-3"
          value={weight}
          options={WEIGHT_FILTERS}
          onChange={setWeight}
        />
      </div>

      {view.selected.length > 0 && (
        <div className="flex flex-col gap-2.5" data-selected-models>
          <MicroLabel>SELECTED</MicroLabel>
          <div className="flex flex-wrap gap-2">
            {view.selected.map((model) => (
              <button
                key={model.id}
                type="button"
                aria-pressed
                onClick={() => toggle(model.id)}
                title={`Remove ${model.displayName}`}
                className="flex h-8 items-center gap-2 rounded-xs border border-accent-700 bg-accent-900 py-0 pl-1.5 pr-2 text-[13px] font-medium text-text transition-colors hover:border-accent-500"
              >
                <InitialsBadge initials={model.monogram} size={20} tone="base" />
                <span className="max-w-[180px] truncate">{model.displayName}</span>
                <X size={12} className="flex-none text-neutral-400" aria-hidden />
              </button>
            ))}
          </div>
        </div>
      )}

      {currentSections.map(renderSection)}

      {view.empty && (
        <p
          role="status"
          className="m-0 py-5 text-[14px] leading-[1.5] text-neutral-400"
        >
          {view.empty === 'registry'
            ? 'No models are available. Ask an Admin to enable one.'
            : searching
              ? `No models match “${query.trim()}”.`
              : 'No models match these filters.'}
        </p>
      )}

      {view.previousMatches > 0 && !searching && (
        <button
          type="button"
          aria-expanded={showPrevious}
          onClick={() => setShowPrevious((current) => !current)}
          className="-ml-2.5 flex h-8 items-center gap-2 self-start rounded-xs px-2.5 text-[13px] font-medium text-neutral-300 transition-colors hover:bg-surface hover:text-text"
        >
          {showPrevious
            ? `Hide previous releases (${view.previousMatches})`
            : `Show previous releases (${view.previousMatches})`}
          <CaretDown
            size={12}
            className={cn('transition-transform', showPrevious && 'rotate-180')}
            aria-hidden
          />
        </button>
      )}

      {previousSection && renderSection(previousSection)}
    </div>
  );
}

export function NewComparisonClient({
  models,
  handle,
  maxChallengers,
}: {
  models: FormModel[];
  handle: string;
  maxChallengers: number;
}) {
  const router = useRouter();
  const inputRef = useRef<HTMLInputElement>(null);
  const titleTouched = useRef(false);
  const [baseSource, setBaseSource] = useState<BaseSource>('upload');
  const [loaded, setLoaded] = useState<LoadedFile | null>(null);
  const [baseOutput, setBaseOutput] = useState('');
  const [baseModelId, setBaseModelId] = useState('');
  const [prompt, setPrompt] = useState('');
  const [title, setTitle] = useState('');
  const [picked, setPicked] = useState<string[]>([]);
  const [categories, setCategories] = useState<string[]>([]);
  const [effort, setEffort] = useState(2);
  const [dragging, setDragging] = useState(false);
  const [fileError, setFileError] = useState<FormError | null>(null);
  const [modelNotice, setModelNotice] = useState<string | null>(null);
  const [submitError, setSubmitError] = useState<FormError | null>(null);
  const [submitting, setSubmitting] = useState(false);

  // The upload tab compares every Turn; the write tab is always one Turn.
  const turnCount =
    baseSource === 'upload' ? loaded?.imported.turns.length ?? 1 : 1;
  const schedule = describeSchedule({
    baseSource,
    hasFile: Boolean(loaded),
    hasBaseOutput: Boolean(baseOutput.trim()),
    baseModelId: baseModelId || null,
    challengerIds: picked,
    prompt,
    turnCount,
    models,
  });
  const baseModel = models.find((model) => model.id === baseModelId) ?? null;
  const pickedModels = picked
    .map((id) => models.find((model) => model.id === id))
    .filter((model): model is FormModel => Boolean(model));
  const hasBase =
    baseSource === 'upload' ? Boolean(loaded) : Boolean(baseOutput.trim());
  const baseBody =
    baseSource === 'upload' ? loaded?.imported.turns[0]?.baseOutput : baseOutput;
  const baseSnippet = baseBody?.trim()
    ? summariseMarkdown(baseBody, 180)
    : undefined;
  const previewTurns: ConversationTurnInput[] = (loaded?.imported.turns ?? []).map(
    (turn, index) =>
      index === 0 && loaded?.imported.format !== 'ai-exporter'
        ? { ...turn, prompt }
        : turn,
  );
  // Write mode has one Turn, and its Prompt is the whole input estimate.
  const estimateTurns: ConversationTurnInput[] =
    baseSource === 'upload' ? previewTurns : [{ prompt, baseOutput }];
  const estimatedTokens = estimateConversationInputTokens(estimateTurns);
  const estimatedCalls = estimateConversationCalls(
    baseSource === 'upload' ? previewTurns.length : 1,
    picked.length,
  );
  const stepOneDone =
    baseSource === 'upload'
      ? Boolean(loaded && baseModelId && prompt.trim())
      : Boolean(prompt.trim() && baseModelId && baseOutput.trim());
  const submitHint =
    baseSource === 'write' && !baseOutput.trim()
      ? 'Paste what the base model wrote to continue'
      : schedule.hint;

  async function loadFile(
    nextFile: File,
    overrides?: { title?: string; categories?: string[] },
  ) {
    setFileError(null);
    try {
      validateFileSize(nextFile.size);
      const text = decodeUtf8(new Uint8Array(await nextFile.arrayBuffer()));
      const imported = parseConversationUpload(text, nextFile.name);
      const matched = matchModelFromFrontMatter(imported.model, models);
      const vendorMatches = matchVendorModels(imported.vendor, models);
      const soleVendorMatch =
        vendorMatches.length === 1 ? vendorMatches[0]! : null;

      setLoaded({
        file: nextFile,
        imported,
        sizeLabel: sizeLabel(nextFile.size, text),
      });
      setPrompt(imported.turns[0]?.prompt ?? imported.prompt ?? '');
      setTitle(overrides?.title ?? defaultTitleForImport(imported));
      titleTouched.current = Boolean(overrides?.title);
      if (overrides?.categories) setCategories(overrides.categories);

      if (matched) {
        setBaseModelId(matched.id);
        setPicked((current) => current.filter((id) => id !== matched.id));
        setModelNotice(null);
      } else if (soleVendorMatch) {
        setBaseModelId(soleVendorMatch.id);
        setPicked((current) => current.filter((id) => id !== soleVendorMatch.id));
        setModelNotice(
          `This looks like a ${vendorLabel(imported.vendor)} conversation, so we selected ${soleVendorMatch.displayName}. Change it if another model wrote the replies.`,
        );
      } else if (imported.vendor) {
        setBaseModelId('');
        const name = vendorLabel(imported.vendor);
        setModelNotice(
          vendorMatches.length > 1
            ? `This looks like a ${name} conversation, which matches ${vendorMatches.length} models in the registry. Choose the one that generated the replies.`
            : `This looks like a ${name} conversation, but no registry model matches it. Choose the model that generated the replies.`,
        );
      } else if (imported.model) {
        setBaseModelId('');
        setModelNotice(
          `We couldn't match “${imported.model}” to a model in the registry. Choose the model that generated this output.`,
        );
      } else {
        setModelNotice(null);
      }
    } catch (error) {
      setFileError(
        error instanceof UploadValidationError
          ? { code: error.code, message: error.message }
          : {
              code: 'unreadable_file',
              message:
                'That file could not be read as text. Export the conversation as markdown and try again.',
            },
      );
    }
  }

  function pickFile(file: File | undefined) {
    if (file) void loadFile(file);
  }

  function changePrompt(next: string) {
    setPrompt(next);
    // A bare markdown upload has no Prompt until the author types one, so keep
    // following it with the default title until the title is edited by hand.
    if (!titleTouched.current) {
      setTitle(summariseMarkdown(next, 80) || loaded?.imported.titleFromFile || '');
    }
  }

  function chooseBaseModel(next: string) {
    setBaseModelId(next);
    setModelNotice(null);
    setPicked((current) => current.filter((id) => id !== next));
  }

  function toggleCategory(category: string) {
    setCategories((current) =>
      current.includes(category)
        ? current.filter((value) => value !== category)
        : [...current, category],
    );
  }

  async function submit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!schedule.ready || submitting) return;

    setSubmitError(null);
    setSubmitting(true);

    try {
      const body = new FormData();
      if (baseSource === 'upload' && loaded) {
        body.set('file', loaded.file);
      } else {
        body.set('base_output', baseOutput);
      }
      body.set('base_model_id', baseModelId);
      body.set('prompt', prompt);
      body.set('title', title);
      body.set('effort', String(effort));
      for (const category of categories) body.append('categories', category);
      for (const modelId of picked) body.append('model_ids', modelId);

      const response = await fetch('/api/comparisons', { method: 'POST', body });
      const payload = (await response.json().catch(() => null)) as
        | { id?: string; error?: { code?: string; message?: string } }
        | null;

      if (!response.ok || !payload?.id) {
        const failure = new Error(
          payload?.error?.message ?? 'Could not schedule this comparison. Try again.',
        ) as Error & { code?: string };
        failure.code = payload?.error?.code;
        throw failure;
      }

      router.push(`/comparisons/${payload.id}/job`);
    } catch (error) {
      setSubmitError({
        code:
          error instanceof UploadValidationError
            ? error.code
            : error instanceof Error && 'code' in error && error.code
              ? String(error.code)
              : 'schedule_failed',
        message:
          error instanceof Error
            ? error.message
            : 'Could not schedule this comparison. Try again.',
      });
      setSubmitting(false);
    }
  }

  return (
    <div className="flex min-h-screen flex-col">
      <SiteHeader handle={handle} variant="page" showNew={false} />

      <main className="mx-auto flex w-full max-w-[1200px] flex-wrap items-start gap-x-12 gap-y-10 px-8 pb-20 pt-10">
        <form
          onSubmit={submit}
          className="flex min-w-0 shrink grow-[999] basis-[520px] flex-col gap-6"
        >
          <div className="flex flex-col gap-2.5 pb-2">
            <h1 className="m-0 font-heading text-[30px] font-medium leading-[1.15] tracking-[-0.02em]">
              New comparison
            </h1>
            <span className="max-w-[600px] text-[14.5px] font-normal leading-[1.6] text-neutral-300 [text-wrap:pretty]">
              Upload a conversation or write one prompt, then pick who to compare it
              against. We&apos;ll send every turn to each model&apos;s hosted API.
            </span>
          </div>

          <section className="flex flex-col gap-5 rounded-lg border border-neutral-700 bg-bg p-6">
            <StepHeader number={1} title="Base output" done={stepOneDone}>
              <SegmentedControl
                label="Base output source"
                className="ml-auto w-full flex-col sm:w-auto sm:flex-row"
                itemClassName="h-[30px] px-2.5 sm:px-3"
                value={baseSource}
                options={[
                  {
                    value: 'upload',
                    label: 'Upload a conversation',
                    icon: <UploadSimple size={14} aria-hidden />,
                  },
                  {
                    value: 'write',
                    label: 'Write a prompt',
                    icon: <PencilSimple size={14} aria-hidden />,
                  },
                ]}
                onChange={(next) => {
                  setBaseSource(next);
                  setSubmitError(null);
                }}
              />
            </StepHeader>

            <input
              ref={inputRef}
              type="file"
              accept=".md,.markdown,.txt"
              aria-label="Base output file"
              className="sr-only"
              onChange={(event) => {
                pickFile(event.target.files?.[0]);
                event.target.value = '';
              }}
            />

            {baseSource === 'upload' ? (
              <>
                {!loaded ? (
                  <>
                    <button
                      type="button"
                      onClick={() => inputRef.current?.click()}
                      onDragOver={(event) => {
                        event.preventDefault();
                        setDragging(true);
                      }}
                      onDragLeave={() => setDragging(false)}
                      onDrop={(event) => {
                        event.preventDefault();
                        setDragging(false);
                        pickFile(event.dataTransfer.files[0]);
                      }}
                      className={cn(
                        'flex w-full flex-col items-center gap-2.5 rounded-lg border-[1.5px] border-dashed px-6 py-10 text-center transition-colors',
                        dragging
                          ? 'border-accent bg-accent-900'
                          : 'border-neutral-600 bg-surface hover:border-accent-600',
                      )}
                    >
                      <UploadSimple size={26} className="text-neutral-300" aria-hidden />
                      <span className="text-[15px] font-medium text-text">
                        Drop a .md file, or{' '}
                        <span className="text-accent-300">browse</span>
                      </span>
                      <span className="max-w-[420px] text-[13px] font-normal leading-[1.55] text-neutral-400">
                        AI Exporter, front-matter{' '}
                        <code className="font-mono text-[12px] text-neutral-200">
                          prompt:
                        </code>{' '}
                        and plain markdown are read automatically
                      </span>
                    </button>
                    <HowToGetThisFile />
                  </>
                ) : (
                  <div className="flex flex-col gap-5">
                    <div className="flex items-center gap-3.5 rounded-lg border border-neutral-800 bg-surface px-4 py-3.5">
                      <span className="grid h-9 w-9 flex-none place-items-center rounded-xs bg-accent-900 text-accent-200">
                        <FileText size={18} aria-hidden />
                      </span>
                      <div className="flex min-w-0 flex-1 flex-col gap-0.5">
                        <span className="truncate text-[14.5px] font-medium">
                          {loaded.file.name}
                        </span>
                        <span className={cn('truncate', FIELD_HINT)}>
                          {loaded.sizeLabel} · {plural(previewTurns.length, 'turn')}
                        </span>
                      </div>
                      <button
                        type="button"
                        onClick={() => inputRef.current?.click()}
                        className="btn-secondary flex-none"
                      >
                        Replace
                      </button>
                    </div>

                    <div
                      className={cn(
                        'grid gap-4',
                        loaded.imported.format !== 'ai-exporter' &&
                          '[grid-template-columns:repeat(auto-fit,minmax(240px,1fr))]',
                      )}
                    >
                      <BaseModelSelect
                        models={models}
                        value={baseModelId}
                        onChange={chooseBaseModel}
                      />

                      {loaded.imported.format !== 'ai-exporter' && (
                        <PromptEditor
                          value={prompt}
                          onChange={changePrompt}
                          label={`Prompt${loaded.imported.prompt ? ' · from front-matter' : ''}`}
                        />
                      )}
                    </div>

                    <section
                      aria-label={`Imported ${plural(previewTurns.length, 'turn')}`}
                      className="flex flex-col gap-3"
                    >
                      <div className="flex items-baseline justify-between gap-3">
                        <span className={FIELD_LABEL}>
                          Check every turn before scheduling
                        </span>
                        <span className={FIELD_HINT}>
                          {plural(previewTurns.length, 'turn')}
                        </span>
                      </div>

                      <ol className="m-0 flex list-none flex-col gap-2.5 p-0">
                        {previewTurns.map((turn, index) => (
                          <li
                            key={`${index}-${turn.prompt.slice(0, 12)}`}
                            className="flex flex-col gap-3.5 rounded-lg border border-neutral-800 bg-surface px-5 py-[18px]"
                          >
                            <MicroLabel>Turn {index + 1}</MicroLabel>
                            <p className="m-0 max-w-[85%] self-end rounded-bubble bg-neutral-800 px-3.5 py-2.5 text-[14px] leading-[1.55] text-text [overflow-wrap:anywhere] [text-wrap:pretty]">
                              {summariseMarkdown(turn.prompt, 400) ||
                                'The Prompt field above will be used.'}
                            </p>
                            <div className="flex flex-col gap-1.5">
                              <span className="text-[12.5px] font-medium text-neutral-400">
                                Reply
                                {loaded.imported.vendors[index] ? (
                                  <span className="font-normal">
                                    {' '}
                                    · {vendorLabel(loaded.imported.vendors[index]!)}
                                  </span>
                                ) : null}
                              </span>
                              <p className="m-0 line-clamp-3 text-[14px] leading-[1.65] text-neutral-200 [overflow-wrap:anywhere]">
                                {summariseMarkdown(turn.baseOutput, 300)}
                              </p>
                            </div>
                          </li>
                        ))}
                      </ol>
                    </section>

                    {loaded.imported.warnings.map((warning) => (
                      <p
                        key={`${warning.code}-${warning.message}`}
                        role="status"
                        className="m-0 flex items-start gap-2 text-[13px] font-normal leading-[1.5] text-neutral-200"
                      >
                        <WarningCircle
                          size={14}
                          className="mt-0.5 flex-none text-accent-300"
                          aria-hidden
                        />
                        {warning.message}
                      </p>
                    ))}

                    {modelNotice && (
                      <p
                        role="status"
                        className="m-0 flex items-start gap-2 text-[13px] font-normal leading-[1.5] text-neutral-300"
                      >
                        <WarningCircle
                          size={14}
                          className="mt-0.5 flex-none text-accent-300"
                          aria-hidden
                        />
                        {modelNotice}
                      </p>
                    )}
                  </div>
                )}
              </>
            ) : (
              <div className="flex flex-col gap-5">
                <BaseModelSelect
                  models={models}
                  value={baseModelId}
                  onChange={chooseBaseModel}
                />

                <PromptEditor
                  value={prompt}
                  onChange={changePrompt}
                  label="Prompt"
                  aside={`${prompt.length.toLocaleString('en-US')} / 10,000`}
                  rows={5}
                  placeholder="Write the prompt every model will answer…"
                />

                <label className="flex flex-col gap-2">
                  <span className={FIELD_LABEL}>Base output</span>
                  <textarea
                    value={baseOutput}
                    onChange={(event) => setBaseOutput(event.target.value)}
                    rows={6}
                    maxLength={MAX_BASE_OUTPUT_CHARS}
                    placeholder="Paste what the base model wrote…"
                    className={cn(
                      FIELD_INPUT,
                      'resize-y py-2.5 text-[14px] leading-[1.6]',
                    )}
                  />
                </label>
              </div>
            )}

            {baseSource === 'upload' && fileError && (
              <div
                role="alert"
                className="flex flex-col gap-1 text-[13px] font-normal leading-[1.5] text-danger"
              >
                <p className="m-0 flex items-start gap-2">
                  <WarningCircle size={14} className="mt-0.5 flex-none" aria-hidden />
                  {fileError.message}
                </p>
                <Link
                  href={EXPORT_GUIDE_PATH}
                  className="ml-[22px] font-medium text-accent-300 hover:text-accent-200"
                >
                  See how to fix an export
                </Link>
              </div>
            )}

            {hasBase && (
              <div className="flex flex-col gap-1 pt-1 text-[13px] leading-[1.5] text-neutral-400">
                <p className="m-0 text-neutral-300">
                  {plural(baseSource === 'upload' ? previewTurns.length : 1, 'turn')}
                  {picked.length
                    ? ` × ${plural(picked.length, 'model')} = ${plural(estimatedCalls, 'call')}`
                    : ''}{' '}
                  · ~{estimatedTokens.toLocaleString('en-US')} input tokens per model
                </p>
                <p className="m-0">Limits: {LIMITS_LABEL}</p>
              </div>
            )}
          </section>

          <section className="flex flex-col gap-5 rounded-lg border border-neutral-700 bg-bg p-6">
            <StepHeader
              number={2}
              title="Compare against"
              done={picked.length > 0}
            >
              <span className="ml-auto text-[13px] font-normal text-neutral-400">
                {picked.length} of {maxChallengers} selected
              </span>
            </StepHeader>

            <ChallengerPicker
              models={models}
              baseModelId={baseModelId}
              picked={picked}
              maxChallengers={maxChallengers}
              onChange={setPicked}
            />
          </section>

          <section className="flex flex-col gap-5 rounded-lg border border-neutral-700 bg-bg p-6">
            <StepHeader
              number={3}
              title="Details"
              done={Boolean(title.trim() && categories.length)}
            />

            <label className="flex flex-col gap-2">
              <span className={cn('flex items-baseline justify-between gap-3', FIELD_LABEL)}>
                <span>Title</span>
                <span className={FIELD_HINT}>{title.length} / 200</span>
              </span>
              <input
                value={title}
                onChange={(event) => {
                  titleTouched.current = true;
                  setTitle(event.target.value);
                }}
                placeholder="What's being compared?"
                maxLength={200}
                className={cn(FIELD_INPUT, 'h-[42px] px-3.5 text-[14.5px]')}
              />
            </label>

            <div className="flex flex-col gap-2.5">
              <span className={FIELD_LABEL}>Categories</span>
              <div className="flex flex-wrap gap-2">
                {CATEGORIES.map((category) => {
                  const selected = categories.includes(category);
                  return (
                    <button
                      key={category}
                      type="button"
                      aria-pressed={selected}
                      onClick={() => toggleCategory(category)}
                      className={cn(
                        'h-8 rounded-xs border px-3.5 text-[13px] font-medium transition-colors',
                        selected
                          ? 'border-accent-600 bg-accent-900 text-accent-200'
                          : 'border-neutral-700 bg-transparent text-neutral-300 hover:border-accent-600',
                      )}
                    >
                      {category}
                    </button>
                  );
                })}
              </div>
            </div>

            <div className="flex flex-col gap-2.5" role="group" aria-label="Effort level">
              <span className={FIELD_LABEL}>Effort level</span>
              <div className="grid grid-cols-3 gap-2">
                {EFFORT_LEVELS.map((level) => {
                  const selected = effort === level.value;
                  return (
                    <button
                      key={level.value}
                      type="button"
                      aria-pressed={selected}
                      onClick={() => setEffort(level.value)}
                      className={cn(
                        'flex flex-col items-start gap-1.5 rounded-xs border px-3.5 py-3 text-left transition-colors',
                        selected
                          ? 'border-accent-600 bg-accent-900'
                          : 'border-neutral-700 hover:border-accent-600',
                      )}
                    >
                      <span className="flex items-center gap-2 text-[14px] font-medium text-text">
                        <EffortGlyph effort={level.value} />
                        {level.label}
                      </span>
                      <span className="text-[12.5px] font-normal text-neutral-400">
                        {level.sub}
                      </span>
                    </button>
                  );
                })}
              </div>
            </div>
          </section>

          {submitError && (
            <div
              role="alert"
              className="flex flex-col gap-1 rounded-lg border border-danger/40 bg-danger-surface px-3.5 py-2.5 text-[13px] font-normal leading-[1.5] text-danger"
            >
              <p className="m-0 flex items-start gap-2">
                <X size={14} className="mt-0.5 flex-none" aria-hidden />
                {submitError.message}
              </p>
              {baseSource === 'upload' && UPLOAD_ERROR_CODES.has(submitError.code) && (
                <Link
                  href={EXPORT_GUIDE_PATH}
                  className="ml-[22px] font-medium text-accent-300 hover:text-accent-200"
                >
                  See how to fix an export
                </Link>
              )}
            </div>
          )}

          <div className="flex flex-wrap items-center gap-4 pt-1">
            <button
              type="submit"
              disabled={!schedule.ready || submitting}
              className="btn-primary btn-lg"
            >
              {submitting ? (
                <CircleNotch size={15} className="anim-spin" aria-hidden />
              ) : (
                <PaperPlaneTilt size={15} aria-hidden />
              )}
              {submitting ? 'Scheduling…' : 'Schedule comparison'}
            </button>
            <span className="text-[13px] font-normal leading-[1.5] text-neutral-400">
              {submitting
                ? 'Creating the job and queueing its turns…'
                : submitHint}
            </span>
          </div>
        </form>

        <ComparisonPreview
          className="shrink grow basis-[280px] max-w-[360px] lg:top-[93px]"
          base={
            baseModel
              ? { name: baseModel.displayName, monogram: baseModel.monogram }
              : null
          }
          challengers={pickedModels.map((model) => ({
            name: model.displayName,
            monogram: model.monogram,
          }))}
          title={title}
          categories={categories}
          effort={effort}
          turnCount={turnCount}
          baseSnippet={baseSnippet}
          status={{ label: 'Draft', tone: 'draft' }}
          handle={handle}
          note="Live preview of the card other people will see."
        />
      </main>
    </div>
  );
}
