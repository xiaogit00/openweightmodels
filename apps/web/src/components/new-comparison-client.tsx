/**
 * A styled listbox for the Base model. The selected Model is shown with its
 * initials and name; the menu groups current and previous releases by weight so
 * an older release is never mistaken for its family's current Model.
 */
function BaseModelSelect({
  models,
  value,
  onChange,
}: {
  models: FormModel[];
  value: string;
  onChange: (modelId: string) => void;
}) {
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement>(null);
  const panelRef = useRef<HTMLDivElement>(null);
  const label = 'Generated by';
  const selected = models.find((model) => model.id === value) ?? null;
  const { current, previous } = splitModelsByRelease(models);
  const groups = [
    {
      label: 'Open weights · current',
      models: current.filter((model) => model.openWeights),
    },
    {
      label: 'Open weights · previous',
      models: previous.filter((model) => model.openWeights),
    },
    {
      label: 'Frontier API · current',
      models: current.filter((model) => !model.openWeights),
    },
    {
      label: 'Frontier API · previous',
      models: previous.filter((model) => !model.openWeights),
    },
  ].filter((group) => group.models.length > 0);

  function options() {
    return Array.from(
      panelRef.current?.querySelectorAll<HTMLElement>('[role="option"]') ?? [],
    );
  }

  function moveTo(index: number) {
    const all = options();
    if (!all.length) return;
    const next = all[Math.max(0, Math.min(all.length - 1, index))];
    for (const option of all) option.tabIndex = -1;
    next.tabIndex = 0;
    next.focus();
  }

  function close(refocus = true) {
    setOpen(false);
    if (refocus) triggerRef.current?.focus();
  }

  function choose(modelId: string) {
    onChange(modelId);
    close();
  }

  // Focus the selected option when the menu opens, and close it on an outside
  // pointer press. Keyboard use is handled by the panel and the trigger.
  useEffect(() => {
    if (!open) return;
    const all = options();
    const selectedIndex = all.findIndex(
      (option) => option.getAttribute('aria-selected') === 'true',
    );
    const first = all[selectedIndex >= 0 ? selectedIndex : 0];
    for (const option of all) option.tabIndex = -1;
    if (first) {
      first.tabIndex = 0;
      first.focus();
    }

    const onPointerDown = (event: PointerEvent) => {
      const target = event.target as Node;
      if (panelRef.current?.contains(target) || triggerRef.current?.contains(target)) {
        return;
      }
      setOpen(false);
    };
    document.addEventListener('pointerdown', onPointerDown);
    return () => document.removeEventListener('pointerdown', onPointerDown);
    // `options` reads the panel that only exists while open.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open]);

  function onPanelKeyDown(event: React.KeyboardEvent<HTMLDivElement>) {
    const all = options();
    const index = all.indexOf(document.activeElement as HTMLElement);
    switch (event.key) {
      case 'ArrowDown':
        event.preventDefault();
        moveTo(index + 1);
        break;
      case 'ArrowUp':
        event.preventDefault();
        moveTo(index - 1);
        break;
      case 'Home':
        event.preventDefault();
        moveTo(0);
        break;
      case 'End':
        event.preventDefault();
        moveTo(all.length - 1);
        break;
      case 'Escape':
        event.preventDefault();
        close();
        break;
      case 'Tab':
        // Let focus return to the trigger rather than stranding it on a menu
        // that is about to unmount; the next Tab moves on to the next field.
        event.preventDefault();
        close();
        break;
    }
  }

  return (
    <div className="flex min-w-0 flex-col gap-2">
      <span className={FIELD_LABEL}>{label}</span>
      <div className="relative">
        <button
          ref={triggerRef}
          type="button"
          aria-haspopup="listbox"
          aria-expanded={open}
          aria-label={label}
          onClick={() => setOpen((isOpen) => !isOpen)}
          onKeyDown={(event) => {
            if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
              event.preventDefault();
              setOpen(true);
            } else if (event.key === 'Escape' && open) {
              event.preventDefault();
              close();
            }
          }}
          className={cn(
            'flex h-10 w-full items-center gap-2.5 rounded-xs border bg-bg px-3 text-left text-[14px] transition-colors',
            open
              ? 'border-accent'
              : 'border-neutral-700 hover:border-neutral-500',
            selected ? 'text-text' : 'text-neutral-400',
          )}
        >
          {selected ? (
            <InitialsBadge initials={selected.monogram} size={20} tone="base" />
          ) : null}
          <span className="min-w-0 flex-1 truncate">
            {selected
              ? `${selected.displayName}${selected.release === 'previous' ? ' (previous)' : ''}`
              : 'Select model…'}
          </span>
          <CaretDown size={13} className="flex-none text-neutral-400" aria-hidden />
        </button>

        {open && (
          <div
            ref={panelRef}
            role="listbox"
            aria-label={label}
            onKeyDown={onPanelKeyDown}
            className="popover-surface absolute inset-x-0 top-[calc(100%+6px)] z-30 max-h-[340px] gap-0 overflow-y-auto p-1.5"
          >
            <button
              type="button"
              role="option"
              aria-selected={!value}
              tabIndex={-1}
              onClick={() => choose('')}
              className={cn(
                'flex h-[34px] w-full items-center rounded-xs px-2 text-left text-[13.5px] text-neutral-400 hover:bg-neutral-800',
                !value && 'bg-neutral-800',
              )}
            >
              <span className="min-w-0 flex-1">Select model…</span>
              {!value && (
                <Check
                  size={14}
                  weight="bold"
                  className="flex-none text-accent-300"
                  aria-hidden
                />
              )}
            </button>
            {groups.map((group) => (
              <div key={group.label} role="group" aria-label={group.label}>
                <div aria-hidden className="micro-label px-2 pb-1 pt-2.5">
                  {group.label}
                </div>
                {group.models.map((model) => {
                  const chosen = model.id === value;
                  return (
                    <button
                      key={model.id}
                      type="button"
                      role="option"
                      aria-selected={chosen}
                      tabIndex={-1}
                      onClick={() => choose(model.id)}
                      className={cn(
                        'flex h-[34px] w-full items-center gap-2 rounded-xs px-2 text-left text-[13.5px] text-text transition-colors hover:bg-neutral-800',
                        chosen && 'bg-neutral-800',
                      )}
                    >
                      <span className="min-w-0 flex-1 truncate">
                        {model.displayName}
                        {model.release === 'previous' ? ' (previous)' : ''}
                      </span>
                      {chosen && (
                        <Check
                          size={14}
                          weight="bold"
                          className="flex-none text-accent-300"
                          aria-hidden
                        />
                      )}
                    </button>
                  );
                })}
              </div>
            ))}
            {models.length === 0 && (
              <p className="m-0 px-2 py-3 text-[13px] leading-[1.45] text-neutral-400">
                No models are available. Ask an Admin to enable one.
              </p>
            )}
          </div>
        )}
      </div>
    </div>
  );
}

