import { expect, test } from '@playwright/test';
import { createComparison, publishConversation, signInAs } from './support';

const CURRENT_RELEASES = 16;
const PREVIOUS_RELEASES = 14;
const ENABLED_MODELS = CURRENT_RELEASES + PREVIOUS_RELEASES;

test('the New Comparison pickers reach every current and previous Model', async ({
  page,
}) => {
  await signInAs(page, 'mira');
  await page.goto('/new');
  await page.getByRole('button', { name: 'Write a prompt' }).click();

  const basePicker = page.getByLabel('Generated by');
  // Every enabled Model plus the placeholder. Retired demo rows are gone.
  await expect(basePicker.locator('option')).toHaveCount(ENABLED_MODELS + 1);
  await expect(
    basePicker.locator('option', { hasText: 'Qwen2.5 72B' }),
  ).toHaveCount(0);
  await expect(
    basePicker.locator('option', { hasText: 'DeepSeek V3' }),
  ).toHaveCount(0);

  // Current releases lead, grouped by weights; previous releases are marked.
  await expect(
    basePicker.locator('optgroup[label="Open weights · current"]'),
  ).toHaveCount(1);
  await expect(
    basePicker.locator('optgroup[label="Open weights · previous"]'),
  ).toHaveCount(1);
  await expect(
    basePicker.locator('optgroup[label="Frontier API · current"]'),
  ).toHaveCount(1);
  await expect(
    basePicker.locator('optgroup[label="Frontier API · previous"]'),
  ).toHaveCount(1);
  await expect(
    basePicker.locator('option', { hasText: 'Llama 3.3 70B (previous)' }),
  ).toHaveCount(1);

  await basePicker.selectOption({ label: 'Grok 4.7' });
  await expect(basePicker).toHaveValue(/.+/);

  // Step 2 opens on current releases only, in two weight groups.
  await expect(page.locator('[data-model-section="open-weights"]')).toBeVisible();
  await expect(page.locator('[data-model-section="frontier-api"]')).toBeVisible();
  await expect(page.locator('[data-model-section="previous"]')).toHaveCount(0);
  await expect(
    page.locator('[data-model-section="open-weights"] button').first(),
  ).toBeVisible();

  // The Base model stays in the grid but cannot be picked as a Challenger.
  const baseTile = page
    .locator('[data-model-section="frontier-api"] button')
    .filter({ hasText: 'Grok 4.7' });
  await expect(baseTile).toBeDisabled();
  await expect(baseTile).toContainText('Base model');

  // Search reaches a collapsed previous release and badges it.
  const search = page.getByRole('searchbox', { name: 'Search models' });
  await search.fill('Llama 3.3');
  const previous = page.locator('[data-model-section="previous"]');
  await expect(previous).toBeVisible();
  await expect(previous.locator('[data-previous-badge]')).toHaveCount(1);
  await previous.getByRole('button', { name: /Llama 3\.3 70B/ }).click();

  // Selected Challengers stay pinned when a later search excludes them.
  const selected = page.locator('[data-selected-models]');
  await expect(selected.getByRole('button', { name: /Llama 3\.3 70B/ })).toBeVisible();
  await search.fill('Phi 4');
  await expect(previous).toHaveCount(0);
  await expect(selected.getByRole('button', { name: /Llama 3\.3 70B/ })).toBeVisible();

  // Clearing search folds previous releases away; the disclosure reopens them.
  await search.fill('');
  await expect(previous).toHaveCount(0);
  await page
    .getByRole('button', { name: new RegExp(`Show previous releases \\(${PREVIOUS_RELEASES}\\)`) })
    .click();
  await expect(previous).toBeVisible();
  await expect(previous.locator('[data-previous-badge]')).toHaveCount(PREVIOUS_RELEASES);

  // Deselecting works from the pinned strip.
  await selected.getByRole('button', { name: /Llama 3\.3 70B/ }).click();
  await expect(selected).toHaveCount(0);

  // An empty search says so explicitly.
  await search.fill('no-such-model');
  await expect(page.getByText(/No models match “no-such-model”/)).toBeVisible();
});

test('the New Comparison picker is reachable by keyboard', async ({ page }) => {
  await signInAs(page, 'mira');
  await page.goto('/new');
  await page.getByRole('button', { name: 'Write a prompt' }).click();

  const search = page.getByRole('searchbox', { name: 'Search models' });
  await search.focus();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: 'All', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(
    page.getByRole('button', { name: 'Open weights', exact: true }),
  ).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(
    page.getByRole('button', { name: 'Frontier API', exact: true }),
  ).toBeFocused();

  const currentTiles = page.locator(
    '[data-model-section="open-weights"] button, [data-model-section="frontier-api"] button',
  );
  expect(await currentTiles.count()).toBe(CURRENT_RELEASES);
  const disclosure = page.getByRole('button', { name: /Show previous releases/ });
  // Every current tile is a button in the tab order before the disclosure.
  for (let index = 0; index < 30; index += 1) {
    if (await disclosure.evaluate((element) => element === document.activeElement)) {
      break;
    }
    await page.keyboard.press('Tab');
  }
  await expect(disclosure).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(
    page.getByRole('button', { name: /Hide previous releases/ }),
  ).toHaveAttribute('aria-expanded', 'true');

  // The disclosure sits directly before the previous tiles, which are buttons.
  await page.keyboard.press('Tab');
  await expect(page.locator('[data-model-section="previous"] button').first()).toBeFocused();
});

test('the Add model menu searches and scrolls through every eligible Model', async ({
  page,
}) => {
  await signInAs(page, 'ana');
  const comparisonId = await createComparison(
    page,
    `E2E picker menu ${Date.now()}`,
  );
  await publishConversation(page, comparisonId);
  await page.goto(`/comparisons/${comparisonId}`);

  const addButton = page.getByRole('button', { name: 'Add model' });
  await addButton.click();
  const menu = page.locator('[data-add-menu]');
  await expect(menu).toBeVisible();
  const search = menu.getByRole('searchbox', { name: 'Search models' });
  await expect(search).toBeFocused();

  const list = menu.locator('[data-add-model-list]');
  const metrics = await list.evaluate((element) => ({
    maxHeight: getComputedStyle(element).maxHeight,
    overflowY: getComputedStyle(element).overflowY,
    rows: element.querySelectorAll('button').length,
  }));
  expect(metrics.maxHeight).not.toBe('none');
  expect(metrics.overflowY).toBe('auto');
  // The fixture's Base and existing Challenger are not offered.
  expect(metrics.rows).toBe(ENABLED_MODELS - 2);

  await search.fill('Fixture Base');
  await expect(menu.getByText(/No models match/)).toBeVisible();
  await search.fill('Qwen3.8 27B');
  await expect(menu.getByText(/No models match/)).toBeVisible();

  // Search by slug reaches a Model near the end of the registry.
  await search.fill('gpt-oss-120b');
  const target = list.getByRole('button', { name: /gpt-oss-120b/ });
  await expect(target).toBeVisible();
  await target.click();
  await expect(
    page.locator('[data-challenger-tab="gpt-oss-120b"]'),
  ).toBeVisible();

  // Escape closes the popover and returns focus to its trigger.
  await addButton.click();
  await expect(menu).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(menu).toBeHidden();
  await expect(addButton).toBeFocused();
});
