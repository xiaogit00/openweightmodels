import { expect, test } from '@playwright/test';
import { createComparison, publishConversation, signInAs } from './support';

const ENABLED_MODELS = 50;

test('the New Comparison pickers browse every Model by Weight class', async ({
  page,
}) => {
  await signInAs(page, 'mira');
  await page.goto('/new');
  await page.getByRole('button', { name: 'Write a prompt' }).click();

  const basePicker = page.getByLabel('Generated by');
  await basePicker.click();
  const listbox = page.getByRole('listbox', { name: 'Generated by' });
  // Every enabled Model plus the placeholder. Retired demo rows are gone.
  await expect(listbox.getByRole('option')).toHaveCount(ENABLED_MODELS + 1);
  await expect(listbox.getByRole('option', { name: 'Qwen2.5 72B' })).toHaveCount(0);
  await expect(listbox.getByRole('option', { name: 'DeepSeek V3' })).toHaveCount(0);

  // The menu groups by Weight class, then Frontier. Models are peers, so a
  // formerly "previous" release carries no marker.
  await expect(listbox.getByRole('group', { name: 'Open weights · Fly' })).toBeVisible();
  await expect(
    listbox.getByRole('group', { name: 'Open weights · Super Heavy' }),
  ).toBeVisible();
  await expect(listbox.getByRole('group', { name: 'Frontier API' })).toBeVisible();
  const llama = listbox.getByRole('option', { name: 'Llama 3.3 70B' });
  await expect(llama).toBeVisible();
  await expect(listbox.getByRole('option', { name: /\(previous\)/ })).toHaveCount(0);

  await listbox.getByRole('option', { name: 'Grok 4.7' }).click();
  await expect(basePicker).toContainText('Grok 4.7');

  // Step 2 opens on All sizes with one tab per populated class plus Frontier.
  const tablist = page.getByRole('tablist', { name: 'Weight class' });
  await expect(tablist.getByRole('tab')).toHaveCount(8);
  await expect(tablist.getByRole('tab', { name: /All sizes/ })).toHaveAttribute(
    'aria-selected',
    'true',
  );
  for (const key of ['fly', 'feather', 'light', 'middle', 'heavy', 'super-heavy', 'frontier']) {
    await expect(page.locator(`[data-model-section="${key}"]`)).toBeVisible();
  }
  await expect(page.locator('[data-model-section="previous"]')).toHaveCount(0);

  // The Base model stays in the grid but cannot be picked as a Challenger.
  const baseTile = page
    .locator('[data-weight-class="frontier"]')
    .filter({ hasText: 'Grok 4.7' });
  await expect(baseTile).toBeDisabled();
  await expect(baseTile).toContainText('Base model');
  await expect(baseTile).toContainText('Size undisclosed');

  // A class tab shows only its section and keeps the tab in the URL.
  await tablist.getByRole('tab', { name: /Light/ }).click();
  await expect(page.locator('[data-model-section="light"]')).toBeVisible();
  await expect(page.locator('[data-model-section="fly"]')).toHaveCount(0);
  await expect(page).toHaveURL(/class=light/);
  const lightCard = page
    .locator('[data-model-section="light"] button')
    .filter({ hasText: 'Qwen3.8 27B' });
  await expect(lightCard).toContainText('Alibaba · 27B');
  await expect(lightCard.locator('[data-memory-bar]')).toBeVisible();
  await expect(lightCard).toContainText('32 GB');

  // A reload restores the tab from ?class=.
  await page.reload();
  await expect(
    page.getByRole('tab', { name: /Light/ }),
  ).toHaveAttribute('aria-selected', 'true');
  await expect(page.locator('[data-model-section="light"]')).toBeVisible();

  // A Model that used to be hidden as a "previous release" is now an ordinary
  // peer, reachable through its class.
  await page.getByRole('tab', { name: /Middle/ }).click();
  await expect(
    page
      .locator('[data-model-section="middle"]')
      .getByRole('button', { name: /Llama 3\.3 70B/ }),
  ).toBeVisible();

  // Selecting from different tabs pins every Challenger and keeps the cap.
  await page.getByRole('tab', { name: /All sizes/ }).click();
  await page.getByRole('button', { name: /Qwen3\.8 27B/ }).click();
  await page.getByRole('button', { name: /Llama 3\.3 70B/ }).click();
  await page.getByRole('button', { name: /Phi 4/ }).click();
  await page.getByRole('button', { name: /Gemma 4 31B/ }).click();
  const selected = page.locator('[data-selected-models]');
  await expect(selected.getByRole('button')).toHaveCount(4);
  await expect(selected.locator('[data-size-glyph]')).toHaveCount(4);
  await page.getByRole('tab', { name: /Light/ }).click();
  await expect(
    page.locator('[data-weight-class="light"]').filter({ hasText: 'Gemma 3 27B' }),
  ).toBeDisabled();

  // Search spans class labels on All sizes, and applies within a class tab.
  await page.getByRole('tab', { name: /All sizes/ }).click();
  const search = page.getByRole('searchbox', { name: 'Search models' });
  await search.fill('heavy');
  await expect(page.locator('[data-model-section="heavy"]')).toBeVisible();
  await expect(page.locator('[data-model-section="super-heavy"]')).toBeVisible();
  await expect(page.locator('[data-model-section="light"]')).toHaveCount(0);

  await page.getByRole('tab', { name: /Fly/ }).click();
  await search.fill('qwen');
  await expect(page.getByText('No models match “qwen” in Fly weight.')).toBeVisible();
  await expect(
    page.getByText(/Size is the memory to run a model yourself at 4-bit/),
  ).toBeVisible();
});

test('the Weight-class tab bar is reachable by keyboard', async ({ page }) => {
  await signInAs(page, 'mira');
  await page.goto('/new');
  await page.getByRole('button', { name: 'Write a prompt' }).click();

  const allSizes = page.getByRole('tab', { name: /All sizes/ });
  await allSizes.focus();
  await page.keyboard.press('ArrowRight');
  const fly = page.getByRole('tab', { name: /Fly/ });
  await expect(fly).toHaveAttribute('aria-selected', 'true');
  await expect(fly).toBeFocused();

  await page.keyboard.press('End');
  const frontier = page.getByRole('tab', { name: /Frontier/ });
  await expect(frontier).toHaveAttribute('aria-selected', 'true');
  await expect(frontier).toBeFocused();

  await page.keyboard.press('Home');
  await expect(allSizes).toHaveAttribute('aria-selected', 'true');
  await expect(allSizes).toBeFocused();
});

test('the Add model menu groups by class and searches through every eligible Model', async ({
  page,
}) => {
  await signInAs(page, 'ana');
  const comparisonId = await createComparison(page, `E2E picker menu ${Date.now()}`);
  await publishConversation(page, comparisonId);
  await page.goto(`/comparisons/${comparisonId}`);

  const addButton = page.locator('[data-add-button]');
  await addButton.click();
  const menu = page.locator('[data-add-menu]');
  await expect(menu).toBeVisible();
  const search = menu.getByRole('searchbox', { name: 'Search models' });
  await expect(search).toBeFocused();

  const list = menu.locator('[data-add-model-list]');
  await expect(list.getByRole('group', { name: 'Fly weight' })).toBeVisible();
  await expect(list.getByRole('group', { name: 'Super Heavy weight' })).toBeVisible();
  await expect(list.getByRole('group', { name: 'Frontier API' })).toBeVisible();

  const metrics = await list.evaluate((element) => ({
    maxHeight: getComputedStyle(element).maxHeight,
    overflowY: getComputedStyle(element).overflowY,
    rows: element.querySelectorAll('button').length,
  }));
  expect(metrics.maxHeight).not.toBe('none');
  expect(metrics.overflowY).toBe('auto');
  // The fixture's Base and existing Challenger are not offered.
  expect(metrics.rows).toBe(ENABLED_MODELS - 2);

  await search.fill('Fixture Base');
  await expect(menu.getByText(/No models match/)).toBeVisible();
  await search.fill('Qwen3.8 27B');
  await expect(menu.getByText(/No models match/)).toBeVisible();

  // Search by slug reaches a Model near the end of the registry.
  await search.fill('gpt-oss-120b');
  const target = list.getByRole('button', { name: /gpt-oss-120b/ });
  await expect(target).toBeVisible();
  await target.click();
  await expect(menu).toBeHidden();
  await addButton.click();
  await expect(page.locator('[data-challenger-tab="gpt-oss-120b"]')).toBeVisible();
  await page.keyboard.press('Escape');

  // Escape closes the popover and returns focus to its trigger.
  await addButton.click();
  await expect(menu).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(menu).toBeHidden();
  await expect(addButton).toBeFocused();
});
