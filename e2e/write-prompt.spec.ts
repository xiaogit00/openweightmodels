import { expect, test } from '@playwright/test';

test('write a prompt, paste a reply, schedule and publish a one-Turn Comparison', async ({
  page,
}) => {
  const title = `E2E written prompt ${Date.now()}`;
  const prompt = 'Explain a sliding-window rate limiter in Go.';
  const reply =
    'A sliding window keeps one timestamp per accepted request and trims the list on every call.';

  const signedIn = await page.request.post('/api/dev/user', { data: { handle: 'mira' } });
  expect(signedIn.ok()).toBeTruthy();

  await page.goto('/new');
  await page.getByRole('button', { name: 'Write a prompt' }).click();

  await page
    .getByPlaceholder('Write the prompt every model will answer…')
    .fill(prompt);
  await page
    .getByPlaceholder('Paste what the base model wrote…')
    .fill(reply);
  await page.getByPlaceholder("What's being compared?").fill(title);

  // Closed frontier Models are visibly distinct from open-weight ones in both
  // pickers, so a reader is never misled about what ran.
  const basePicker = page.getByLabel('Generated by');
  await basePicker.click();
  const listbox = page.getByRole('listbox', { name: 'Generated by' });
  await expect(
    listbox.getByRole('group', { name: 'Open weights · Fly' }),
  ).toBeVisible();
  await expect(
    listbox.getByRole('group', { name: 'Open weights · Super Heavy' }),
  ).toBeVisible();
  await expect(listbox.getByRole('group', { name: 'Frontier API' })).toBeVisible();
  await expect(
    listbox
      .getByRole('group', { name: 'Frontier API' })
      .getByRole('option', { name: 'Claude Opus 5.5' }),
  ).toBeVisible();
  // Every Model is a peer: no previous-release marker and no disclosure.
  const middleLlama = listbox.getByRole('option', { name: 'Llama 3.3 70B' });
  await expect(middleLlama).toBeVisible();
  await middleLlama.click();
  await expect(basePicker).toContainText('Llama 3.3 70B');
  await expect(basePicker).not.toContainText('(previous)');
  await expect(
    page
      .locator('[data-weight-class="frontier"]')
      .filter({ hasText: 'Claude Opus 5.5' }),
  ).toContainText('Anthropic');
  await expect(
    page.locator('[data-weight-class="light"]').filter({ hasText: 'Qwen3.8 27B' }),
  ).toContainText('Alibaba');
  await page.getByRole('button', { name: /Qwen3\.8 27B/ }).click();
  await page.getByRole('button', { name: 'Coding', exact: true }).click();

  await page.getByRole('button', { name: 'Schedule comparison' }).click();
  await expect(page).toHaveURL(/\/comparisons\/[^/]+\/job$/, { timeout: 30_000 });

  await expect(page.getByText('Your comparison is ready')).toBeVisible({ timeout: 90_000 });

  await page.getByRole('button', { name: 'Publish to board' }).click();
  await expect(page.getByRole('heading', { name: title })).toBeVisible();
  await expect(page.getByText(reply)).toBeVisible();
  // Locked decision 4: the Prompt disclosure is gone. The Prompt is shown once
  // per response column instead, so it is already on screen.
  await expect(page.getByText(prompt).first()).toBeVisible();
});
