import { expect, test } from '@playwright/test';

test('write a prompt, paste a reply, schedule and publish a one-Turn Comparison', async ({
  page,
}) => {
  const title = `E2E written prompt ${Date.now()}`;
  const prompt = 'Explain a sliding-window rate limiter in Go.';
  const reply =
    'A sliding window keeps one timestamp per accepted request and trims the list on every call.';

  const signedIn = await page.request.post('/api/dev/user', { data: { handle: 'mira' } });
  expect(signedIn.ok()).toBeTruthy();

  await page.goto('/new');
  await page.getByRole('button', { name: 'Write a prompt' }).click();

  await page.getByPlaceholder('Ask the model something…').fill(prompt);
  await page
    .getByPlaceholder('Paste what the base model wrote…')
    .fill(reply);
  await page.getByLabel('Generated by').selectOption({ label: 'Llama 3.3 70B (previous)' });
  await page.getByPlaceholder("What's being compared?").fill(title);

  // Closed frontier Models are visibly distinct from open-weight ones in both
  // pickers, so a reader is never misled about what ran.
  const basePicker = page.getByLabel('Generated by');
  await expect(basePicker.locator('optgroup[label="Open weights · current"]')).toHaveCount(1);
  await expect(basePicker.locator('optgroup[label="Open weights · previous"]')).toHaveCount(1);
  await expect(basePicker.locator('optgroup[label="Frontier API · current"]')).toHaveCount(1);
  await expect(basePicker.locator('optgroup[label="Frontier API · previous"]')).toHaveCount(1);
  await expect(
    basePicker.locator('optgroup[label="Frontier API · current"] option', {
      hasText: 'Claude Opus 5.5',
    }),
  ).toHaveCount(1);
  // A previous release stays selectable and is visibly marked as previous.
  await expect(
    basePicker.locator('optgroup[label="Open weights · previous"] option', {
      hasText: 'Llama 3.3 70B (previous)',
    }),
  ).toHaveCount(1);
  await expect(
    page
      .locator('[data-model-weight="frontier"]')
      .filter({ hasText: 'Claude Opus 5.5' }),
  ).toContainText('Frontier API');
  await expect(
    page.locator('[data-model-weight="open"]').filter({ hasText: 'Qwen3.8 27B' }),
  ).toContainText('Open weights');
  await page.getByRole('button', { name: /Qwen3\.8 27B/ }).click();
  await page.getByRole('button', { name: 'Coding', exact: true }).click();

  await page.getByRole('button', { name: 'Schedule comparison' }).click();
  await expect(page).toHaveURL(/\/comparisons\/[^/]+\/job$/, { timeout: 30_000 });

  await expect(page.getByText('Your comparison is ready')).toBeVisible({ timeout: 90_000 });

  await page.getByRole('button', { name: 'Publish to board' }).click();
  await expect(page.getByRole('heading', { name: title })).toBeVisible();
  await expect(page.getByText(reply)).toBeVisible();
  // The Prompt stays collapsed until the reader asks for it.
  await page.getByRole('button', { name: 'Prompt', exact: true }).click();
  await expect(page.getByText(prompt)).toBeVisible();
});
