import { expect, test } from '@playwright/test';
import { publishConversation, signInAs } from './support';

function slugOf(name: string) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

type Model = { id: string; slug: string };

async function fixtureModels(page: import('@playwright/test').Page) {
  const response = await page.request.get('/api/models');
  expect(response.ok()).toBeTruthy();
  const { models } = (await response.json()) as { models: Model[] };
  const base = models.find((model) => model.slug === 'llama-3-3-70b');
  const challenger = models.find((model) => model.slug === 'qwen-3-8-27b');
  expect(base).toBeTruthy();
  expect(challenger).toBeTruthy();
  return { base: base!, challenger: challenger! };
}

async function postWithCategory(
  page: import('@playwright/test').Page,
  data: { title: string; category: string },
) {
  const { base, challenger } = await fixtureModels(page);
  const form = new FormData();
  form.set(
    'file',
    new File(
      [
        [
          '---',
          `prompt: ${data.title} — explain a bounded queue.`,
          'model: llama-3-3-70b',
          '---',
          '',
          'A bounded queue rejects new work once it is full, so memory stays flat.',
        ].join('\n'),
      ],
      'category-base.md',
      { type: 'text/markdown' },
    ),
  );
  form.set('base_model_id', base.id);
  form.set('prompt', `${data.title} — explain a bounded queue.`);
  form.set('title', data.title);
  form.set('effort', '1');
  form.append('categories', data.category);
  form.append('model_ids', challenger.id);

  const response = await page.request.post('/api/comparisons', { multipart: form });
  expect(response.ok()).toBeTruthy();
  const payload = (await response.json()) as { id: string };
  return payload.id;
}

test('an Author creates and reuses a community Category, then filters the Board by it', async ({
  page,
}) => {
  await signInAs(page, 'ana');
  const stamp = Date.now();
  const name = `Niche ${stamp}`;
  const slug = slugOf(name);
  const title = `Community category ${stamp}`;
  const prompt = 'Design a bounded queue with backpressure.';
  const reply = 'A bounded queue keeps memory flat by rejecting writes when full.';

  await page.goto('/new');
  await page.getByRole('button', { name: 'Write a prompt' }).click();
  await page.getByPlaceholder('Write the prompt every model will answer…').fill(prompt);
  await page.getByPlaceholder('Paste what the base model wrote…').fill(reply);
  await page.getByPlaceholder("What's being compared?").fill(title);

  const basePicker = page.getByLabel('Generated by');
  await basePicker.click();
  await page
    .getByRole('listbox', { name: 'Generated by' })
    .getByRole('option', { name: 'Llama 3.3 70B' })
    .click();
  await page.getByRole('button', { name: /Qwen3\.8 27B/ }).click();
  // Click order is the card's label order: Reasoning is chosen before the new
  // name, so the Board card must lead with Reasoning.
  await page.getByRole('button', { name: 'Reasoning', exact: true }).click();

  // Typing a name that nothing matches offers the create row; Enter selects it.
  const combo = page.getByRole('combobox', { name: 'Find or create a category' });
  await combo.click();
  // The seeded library has presets but no community Categories yet, so the
  // empty state explains itself instead of showing an empty list.
  await expect(
    page.getByText('No community categories to browse yet', { exact: false }),
  ).toBeVisible();
  await combo.fill(name);
  await expect(page.locator('[data-category-create]')).toContainText(name);
  await page.keyboard.press('Enter');

  const chip = page.locator(`[data-category-chip="${slug}"]`);
  await expect(chip).toContainText(name);
  await expect(chip).toContainText('New');
  await expect(page.getByText('2 selected')).toBeVisible();

  await page.getByRole('button', { name: 'Schedule comparison' }).click();
  await expect(page).toHaveURL(/\/comparisons\/[^/]+\/job$/, { timeout: 30_000 });
  const firstHref = new URL(page.url()).pathname.replace(/\/job$/, '');
  const firstId = firstHref.split('/').pop()!;
  await expect(page.getByText('Your comparison is ready')).toBeVisible({ timeout: 90_000 });
  await page.getByRole('button', { name: 'Publish to board' }).click();
  await expect(page).toHaveURL(`/comparisons/${firstId}`);
  await expect(page.getByRole('heading', { name: title })).toBeVisible();

  // The same combobox and caps serve the edit form; a published Comparison
  // creates the new Category immediately.
  const editedName = `Edited ${stamp}`;
  const editedSlug = slugOf(editedName);
  await page.getByRole('link', { name: 'Edit details' }).click();
  await expect(page).toHaveURL(`/comparisons/${firstId}/edit`, { timeout: 60_000 });
  await expect(page.getByRole('heading', { name: 'Edit details' })).toBeVisible();
  const editCombo = page.getByRole('combobox', { name: 'Find or create a category' });
  await editCombo.click();
  await editCombo.fill(editedName);
  await page.keyboard.press('Enter');
  await expect(page.locator(`[data-category-chip="${editedSlug}"]`)).toContainText(
    editedName,
  );
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page).toHaveURL(`/comparisons/${firstId}`);
  await expect(page.getByText(editedName)).toBeVisible();

  // The community Category is now public and filterable.
  await page.goto('/');
  const community = page.locator(`aside [data-category-option="${slug}"]`);
  await expect(community).toContainText(name);
  await expect(community.locator('[data-category-count]')).toHaveText('1');
  await community.click();
  await expect(page).toHaveURL(new RegExp(`category=${slug}`));
  const firstCard = page.locator(`main a.card[href="/comparisons/${firstId}"]`);
  await expect(firstCard).toBeVisible();
  await expect(firstCard.locator('[data-card-category]')).toHaveText('Reasoning');

  // Reuse: a second Comparison can pick the existing Category, not create it.
  const secondTitle = `Reused category ${stamp}`;
  const secondId = await postWithCategory(page, { title: secondTitle, category: name });
  await publishConversation(page, secondId);

  await page.goto('/new');
  const reuse = page.getByRole('combobox', { name: 'Find or create a category' });
  await reuse.click();
  await reuse.fill(name);
  const option = page.locator(`[data-category-option="${slug}"]`);
  await expect(option).toBeVisible();
  await expect(option.locator('[data-category-count]')).toHaveText('2');
  await expect(page.locator('[data-category-create]')).toHaveCount(0);

  await page.goto(`/?category=${slug}`);
  await expect(page.locator(`main a.card[href="/comparisons/${firstId}"]`)).toBeVisible();
  await expect(page.locator(`main a.card[href="/comparisons/${secondId}"]`)).toBeVisible();
  await expect(community.locator('[data-category-count]')).toHaveText('2');
});

test('a community Category with no published Comparisons waits behind the Board toggle', async ({
  page,
}) => {
  await signInAs(page, 'ana');
  const stamp = Date.now();
  const name = `Zero ${stamp}`;
  const slug = slugOf(name);
  const title = `Zero category fixture ${stamp}`;

  const comparisonId = await postWithCategory(page, { title, category: name });
  await publishConversation(page, comparisonId);
  const unpublished = await page.request.post(
    `/api/comparisons/${comparisonId}/unpublish`,
  );
  expect(unpublished.ok()).toBeTruthy();

  await page.goto('/');
  const community = page.locator(`aside [data-category-option="${slug}"]`);
  await expect(community).toHaveCount(0);
  const toggle = page.locator('aside [data-category-toggle]');
  await expect(toggle).toBeVisible();
  await toggle.click();
  await expect(community).toBeVisible();
  await expect(community.locator('[data-category-count]')).toHaveText('0');
});

test('an Admin renames and deletes a community Category, while presets stay protected', async ({
  page,
}) => {
  await signInAs(page, 'ana');
  const stamp = Date.now();
  const name = `Admin ${stamp}`;
  const renamed = `Renamed ${stamp}`;
  const slug = slugOf(name);

  const comparisonId = await postWithCategory(page, {
    title: `Admin category fixture ${stamp}`,
    category: name,
  });
  await publishConversation(page, comparisonId);

  await signInAs(page, 'mira');
  await page.goto('/admin');
  const presetRow = page.locator('tr[data-category="coding"]');
  await expect(presetRow).toContainText('Coding');
  await expect(presetRow).toContainText('Protected');
  await expect(presetRow.locator('[data-category-delete]')).toHaveCount(0);

  const row = page.locator(`tr[data-category="${slug}"]`);
  await expect(row).toContainText(name);
  await row.locator('[data-category-rename]').click();
  await page.getByLabel(`Rename ${name}`).fill(renamed);
  await row.locator('[data-category-save]').click();
  await expect(page.locator(`tr[data-category="${slug}"]`)).toContainText(renamed);
  await expect(
    page.getByRole('cell', { name: 'Renamed category', exact: true }),
  ).toBeVisible();

  await page.locator(`tr[data-category="${slug}"]`).locator('[data-category-delete]').click();
  await page
    .locator(`tr[data-category="${slug}"]`)
    .locator('[data-category-confirm]')
    .click();
  await expect(page.locator(`tr[data-category="${slug}"]`)).toHaveCount(0);
  await expect(
    page.getByRole('cell', { name: 'Deleted category', exact: true }),
  ).toBeVisible();
});
