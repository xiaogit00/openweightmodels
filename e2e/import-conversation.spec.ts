import { expect, test } from '@playwright/test';

const exporter = [
  '> From: https://chat.example/abc',
  '',
  '# you asked',
  '',
  'message time: 2026-10-27 18:35:45',
  '',
  'First question about queues',
  '',
  '---',
  '',
  '# you asked',
  '',
  'message time: 2026-10-27 18:35:50',
  '',
  'And a follow-up sent by mistake.',
  '',
  '---',
  '',
  '# deepseek response',
  '',
  'message time: 2026-10-27 18:36:00',
  '',
  'BASE ONE: a queue bounds memory.',
  '',
  '---',
  '',
  '# you asked',
  '',
  'message time: 2026-10-27 18:36:40',
  '',
  'Second question about backpressure',
  '',
  '---',
  '',
  '# deepseek response',
  '',
  'message time: 2026-10-27 18:36:45',
  '',
  'BASE TWO: reject early.',
  '- Keep the queue bounded.',
  '',
  '---',
  'Powered by [AI Exporter](https://saveai.net)',
].join('\n');

test('import an AI Exporter conversation, confirm it, then replay every Turn', async ({
  page,
}) => {
  const title = `E2E imported conversation ${Date.now()}`;

  // Ana keeps this job notification away from the journey's Mira mailbox.
  const signedIn = await page.request.post('/api/dev/user', {
    data: { handle: 'ana' },
  });
  expect(signedIn.ok()).toBeTruthy();

  await page.goto('/new');
  await page.locator('input[type=file]').setInputFiles({
    name: 'DeepSeek_export.md',
    mimeType: 'text/markdown',
    buffer: Buffer.from(exporter),
  });

  // The confirmation shows the Turn count, both kinds of warning and the cost.
  await expect(page.getByText('Turn 1', { exact: true })).toBeVisible();
  await expect(page.getByText('Turn 2', { exact: true })).toBeVisible();
  await expect(page.getByText(/merged into Turn 1/)).toBeVisible();
  await expect(page.getByText(/final reply looks cut off/)).toBeVisible();
  await expect(page.getByText(/input tokens per model/)).toBeVisible();
  await expect(page.getByText(/DeepSeek conversation, which matches 2 models/)).toBeVisible();

  // The title defaults to the first Prompt and stays editable.
  await expect(page.getByLabel('Title')).toHaveValue(/First question about queues/);
  await page.getByLabel('Title').fill(title);

  await page.getByLabel('Generated by').selectOption({ label: 'DeepSeek V3' });
  await page.getByRole('button', { name: /Qwen2\.5 72B/ }).click();
  await page.getByRole('button', { name: 'Coding', exact: true }).click();
  await page.getByRole('button', { name: 'Schedule comparison' }).click();

  await expect(page).toHaveURL(/\/comparisons\/[^/]+\/job$/, { timeout: 30_000 });
  await expect(page.getByText('turn 2 of 2').first()).toBeVisible({ timeout: 30_000 });
  await expect(page.getByText('Your comparison is ready')).toBeVisible({
    timeout: 90_000,
  });

  await page.getByRole('button', { name: 'Publish to board' }).click();
  await expect(page.getByRole('heading', { name: title })).toBeVisible();
  await expect(page.getByText('Turn 1 of 2')).toBeVisible();
  await expect(page.getByText('Turn 2 of 2')).toBeVisible();
  await expect(page.getByText('BASE ONE: a queue bounds memory.').first()).toBeVisible();
  await expect(page.getByText('BASE TWO: reject early.').first()).toBeVisible();

  // Leave the shared seed user's bell as clean as this test found it.
  await page.request.patch('/api/notifications', { data: { all: true } });
});
